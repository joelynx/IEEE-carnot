"""Inline every \\input{...} of main.tex into one standalone .tex file (convenience copy)."""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(sys.argv[2])
base = src.parent
pattern = re.compile(r"^\\input\{([^}]+)\}\s*$")
lines = []
for line in src.read_text(encoding="utf-8").splitlines():
    m = pattern.match(line)
    if m:
        part = base / (m.group(1) + ".tex")
        lines.append(f"% ---- begin {m.group(1)}.tex (inlined) ----")
        lines.extend(part.read_text(encoding="utf-8").rstrip("\n").splitlines())
        lines.append(f"% ---- end {m.group(1)}.tex ----")
    else:
        lines.append(line)
header = ("% Standalone copy of main.tex with tables/ and figures/ inlined; generated by paper/working_notes/verify/flatten.py.\n"
          "% Edit main.tex (the modular source) or this file, but not both.\n")
out.write_bytes((header + "\n".join(lines) + "\n").encode("utf-8"))  # bytes: text mode would write CRLF on Windows
print(out, len(lines), "lines")
